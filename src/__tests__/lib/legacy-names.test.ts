import { describe, it, expect } from "vitest";
import {
  LEGACY_ACTIVITY_ACTIONS,
  LEGACY_AUTO_NAME_PREFIX,
  currentActivityAction,
} from "../../lib/legacy-names";
import { describeCall, isReadAction } from "../../lib/tool-phrases";
import { abbreviateTitle, isAutoGeneratedTitle } from "../../lib/buffer-name";

// Values an earlier build wrote under the product's old name read the same as
// their current spelling (ADR-059 decision 5).

describe("an activity action logged under its old name", () => {
  it("maps to the action it was renamed to", () => {
    for (const [old, current] of LEGACY_ACTIVITY_ACTIONS) {
      expect(currentActivityAction(old)).toBe(current);
    }
  });

  it("passes any other action through unchanged", () => {
    expect(currentActivityAction("read_note")).toBe("read_note");
    expect(currentActivityAction("unknown_tool")).toBe("unknown_tool");
  });

  it("reads in the activity list as its current action does", () => {
    for (const [old, current] of LEGACY_ACTIVITY_ACTIONS) {
      for (const decision of ["allow", "refuse", "pending"] as const) {
        for (const namesFile of [true, false]) {
          expect(describeCall(old, namesFile, decision)).toBe(describeCall(current, namesFile, decision));
        }
      }
      expect(isReadAction(old)).toBe(isReadAction(current));
    }
  });
});

describe("an auto-generated name minted under the old prefix", () => {
  const minted = `${LEGACY_AUTO_NAME_PREFIX}1778473041613`;

  it("is recognised as auto-generated", () => {
    expect(isAutoGeneratedTitle(minted)).toBe(true);
  });

  it("is shortened with the prefix it carries", () => {
    expect(abbreviateTitle(minted)).toBe(`${LEGACY_AUTO_NAME_PREFIX}1613`);
  });
});
