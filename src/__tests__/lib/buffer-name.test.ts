import { describe, it, expect } from "vitest";
import { abbreviateTitle, isAutoGeneratedTitle } from "../../lib/buffer-name";

describe("abbreviateTitle", () => {
  it("abbreviates 13-digit jotra timestamp to jotra-<last4>", () => {
    expect(abbreviateTitle("jotra-1778473041613")).toBe("jotra-1613");
  });

  it("abbreviates longer timestamps to jotra-<last4>", () => {
    expect(abbreviateTitle("jotra-99999999999999")).toBe("jotra-9999");
  });

  it("preserves user-renamed titles", () => {
    expect(abbreviateTitle("my notes")).toBe("my notes");
    expect(abbreviateTitle("scratch.md")).toBe("scratch.md");
  });

  it("preserves jotra titles shorter than 13 digits", () => {
    expect(abbreviateTitle("jotra-12345")).toBe("jotra-12345");
    expect(abbreviateTitle("jotra-1234567890123")).toBe("jotra-0123");
  });

  it("preserves jotra titles with non-digit suffix", () => {
    expect(abbreviateTitle("jotra-1778473041613-foo")).toBe("jotra-1778473041613-foo");
    expect(abbreviateTitle("jotra-notes")).toBe("jotra-notes");
  });

  it("preserves titles that just happen to start with jotra", () => {
    expect(abbreviateTitle("written-notes")).toBe("written-notes");
  });
});

describe("isAutoGeneratedTitle", () => {
  it("returns true for 13-digit jotra timestamps", () => {
    expect(isAutoGeneratedTitle("jotra-1778473041613")).toBe(true);
  });

  it("returns false for user-renamed titles", () => {
    expect(isAutoGeneratedTitle("my notes")).toBe(false);
    expect(isAutoGeneratedTitle("jotra-notes")).toBe(false);
  });

  it("returns false for short numeric suffixes", () => {
    expect(isAutoGeneratedTitle("jotra-1234")).toBe(false);
  });
});
