import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ALLOWLIST = resolve(ROOT, "src/components/Icon/icons.json");
const OUTPUT = resolve(ROOT, "src/components/Icon/sprite.generated.ts");
const ASSETS = resolve(ROOT, "node_modules/@phosphor-icons/core/assets/regular");

const HEADER = "// Generated by scripts/build-icon-sprite.mjs — run `pnpm icons:build`. Do not edit.";

const BOUNDING_RECT = /<rect\s+width="256"\s+height="256"\s+fill="none"\s*\/>/g;
const PAINT_ATTR = /\s(?:fill|stroke)="[^"]*"/g;

function symbolFor(name) {
  const file = resolve(ASSETS, `${name}.svg`);
  let source;
  try {
    source = readFileSync(file, "utf8");
  } catch {
    throw new Error(`icon "${name}" is not in @phosphor-icons/core/assets/regular`);
  }
  const inner = source.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!inner) throw new Error(`icon "${name}" has no <svg> wrapper`);
  const body = inner[1].replace(BOUNDING_RECT, "").replace(PAINT_ATTR, "").trim();
  if (!body) throw new Error(`icon "${name}" is empty once the wrapper is stripped`);
  return `<symbol id="ph-${name}" viewBox="0 0 256 256" fill="currentColor">${body}</symbol>`;
}

function buildSprite() {
  const names = JSON.parse(readFileSync(ALLOWLIST, "utf8"));
  if (!Array.isArray(names) || names.some((n) => typeof n !== "string")) {
    throw new Error("icons.json must be an array of icon names");
  }
  const sorted = [...names].sort();
  if (sorted.join() !== names.join()) throw new Error("icons.json must be sorted");
  const duplicate = sorted.find((name, i) => sorted[i + 1] === name);
  if (duplicate) throw new Error(`icons.json lists "${duplicate}" twice`);

  const sprite = sorted.map(symbolFor).join("");
  return [
    HEADER,
    "",
    `export const ICON_NAMES = ${JSON.stringify(sorted, null, 2)} as const;`,
    "",
    "export type IconName = (typeof ICON_NAMES)[number];",
    "",
    `export const SPRITE = ${JSON.stringify(sprite)};`,
    "",
  ].join("\n");
}

const generated = buildSprite();

if (process.argv.includes("--check")) {
  const committed = readFileSync(OUTPUT, "utf8");
  if (committed !== generated) {
    console.error("sprite.generated.ts is stale — run `pnpm icons:build`");
    process.exit(1);
  }
} else {
  writeFileSync(OUTPUT, generated);
}
